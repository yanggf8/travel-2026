// `travel copy-plan <src_plan_id> <dst_plan_id> [--dry-run]` — copy every row of
// one plan to a new plan id, atomically. Together with `mark-plan-deleted` this
// is how a plan is renamed (plan_id is a key across ~60 tables).
//
// What is copied (all discovered from the LIVE schema, never a hand-kept list):
//   - every table with a `plan_id` column (plan_schema::plan_scoped_tables), with
//     plan_id rewritten — except SKIPPED_TABLES (printed with the reason);
//   - the booking ledger tables (non-plan tables with a `booking_key` column),
//     whose keys start `<trip_id>:` (trip_id = plan_id with '-' -> '_'): the prefix
//     and `trip_id` are rewritten;
//   - activity-keyed tables (non-plan tables with an `activity_id` column, e.g.
//     activity_tags), for the copied activities.
//
// Tables whose PRIMARY KEY does not include the rewritten key: a single INTEGER
// PK is omitted (SQLite assigns one); a single TEXT PK gets a fresh id per row
// from the generator the codebase already uses for that table
// (TEXT_PK_GENERATORS); anything else fails loud. Activity ids are remapped
// everywhere they appear: the activities PK, any text cell equal to an old id
// (e.g. plan_event_data key=activity_id), booking-key segments, activity_tags.
//
// Atomicity: every read (counts, id maps, booking keys) happens first; then all
// writes — the per-table INSERT … SELECT statements and the audit row — run in ONE
// BEGIN … COMMIT on the same remote (hrana) stream, the pattern
// set_companion_route / omiyage already use. Any error ROLLBACKs; a process that
// dies mid-way leaves an open transaction the server discards. Each INSERT's
// affected-row count must equal the planned count, so a source that changed
// between planning and writing aborts the copy instead of half-copying it.
//
// Audit: the new plan's `plans` row carries the source version, then
// record_operation writes one operation_runs row ("copy-plan", "copied from
// <src>") and bumps it to source+1, inside the same transaction. The source plan
// is never written. No plan_events are emitted: like mark-plan-deleted this is a
// plan-lifecycle operation with no process to attach an event to.
//
// Test seam: TRAVEL_COPY_PLAN_FAIL_AT=<table>|commit makes the write phase fail
// right before copying <table> (or right before COMMIT), so the integration test
// can prove a mid-way failure leaves nothing behind. Unset in normal use.

use crate::cascade::common::{new_run_id, now_db_datetime, record_operation};
use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet};
use travel_db::repo::plan_copy::{
    self as pc, CopyStatement, CountItem, IdMap, PkKind, Selection, Source,
};
use travel_db::repo::plan_schema::{self, ColumnInfo};

/// Plan-scoped tables that are deliberately NOT copied, and why.
pub(crate) const SKIPPED_TABLES: &[(&str, &str)] = &[
    (
        "map_artifacts",
        "describes R2 map objects under the source plan's prefix; a copy would let snapshot-maps' input_sha256 reuse skip uploading the new plan's PNGs. Regenerate with snapshot-maps",
    ),
    (
        "map_legend_stops",
        "legend rows of the source plan's R2 maps. Regenerated by snapshot-maps",
    ),
    (
        "plan_map_snapshots",
        "the source plan's map-snapshot stamp. Regenerated by snapshot-maps",
    ),
    (
        "plan_share_tokens",
        "share tokens are per-plan bearer credentials. Mint new ones with share-token",
    ),
];

/// Single-TEXT-PK plan tables and the id generator the codebase already uses
/// for them. A single-TEXT-PK table with rows that is not listed here fails loud
/// rather than getting an invented id format.
const TEXT_PK_GENERATORS: &[(&str, fn() -> String)] = &[
    // add-activity mints ids with set_activity::new_activity_id(), which is the
    // same UUIDv4-shaped run-id generator as cascade::common::new_run_id().
    ("activities", new_run_id),
    // record_operation mints run_ids with cascade::common::new_run_id().
    ("operation_runs", new_run_id),
];

const ACTIVITIES: &str = "activities";
const PLANS: &str = "plans";
const PLAN_ID: &str = "plan_id";
const BOOKING_KEY: &str = "booking_key";
const TRIP_ID: &str = "trip_id";
const ACTIVITY_ID: &str = "activity_id";
const FAULT_ENV: &str = "TRAVEL_COPY_PLAN_FAIL_AT";

pub const USAGE: &str = "travel copy-plan <src_plan_id> <dst_plan_id> [--dry-run]\n  \
Copy every row of a plan to a new plan id in ONE transaction (all or nothing): plan-scoped tables, \
the booking ledger (booking_key prefix + trip_id rewritten) and activity tags; activity ids and other \
non-plan primary keys get fresh ids. Map tables and share tokens are skipped (regenerate them). \
--dry-run prints the per-table counts and writes nothing. Pair with mark-plan-deleted <src> to rename a plan.";

#[derive(Debug, PartialEq)]
struct Args {
    src: String,
    dst: String,
    dry_run: bool,
}

fn parse_args(args: &[String]) -> Result<Args, String> {
    let mut positionals = Vec::new();
    let mut dry_run = false;
    for a in args {
        match a.as_str() {
            "--dry-run" => dry_run = true,
            other if other.starts_with("--") => return Err(format!("unknown argument: {other}")),
            other => positionals.push(other.to_string()),
        }
    }
    if positionals.len() != 2 {
        return Err(format!(
            "copy-plan needs exactly two plan ids (got {}).\nUsage:\n  {USAGE}",
            positionals.len()
        ));
    }
    let dst = positionals.pop().unwrap();
    let src = positionals.pop().unwrap();
    Ok(Args { src, dst, dry_run })
}

/// `^[a-z0-9]+(-[a-z0-9]+)*$` — lowercase alphanumeric words joined by single hyphens.
fn validate_plan_id(id: &str) -> Result<(), String> {
    let ok = !id.is_empty()
        && id
            .split('-')
            .all(|w| !w.is_empty() && w.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit()));
    if ok {
        Ok(())
    } else {
        Err(format!(
            "invalid destination plan id '{id}': use lowercase letters/digits joined by single hyphens (e.g. kyoto-nov-2026)"
        ))
    }
}

/// The booking ledger's trip id for a plan: plan_id with '-' -> '_'.
fn trip_id_of(plan_id: &str) -> String {
    plan_id.replace('-', "_")
}

/// Rewrite `<src_trip>:rest` to `<dst_trip>:rest`, replacing every `:`-separated
/// segment of `rest` that is an old activity id with its new id. `None` when the
/// key does not carry the source prefix.
fn rewrite_booking_key(
    key: &str,
    src_prefix: &str,
    dst_prefix: &str,
    activity_map: &HashMap<&str, &str>,
) -> Option<String> {
    let rest = key.strip_prefix(src_prefix)?;
    let rest: Vec<&str> = rest
        .split(':')
        .map(|seg| activity_map.get(seg).copied().unwrap_or(seg))
        .collect();
    Some(format!("{dst_prefix}{}", rest.join(":")))
}

/// Parents before children over the FK edges among `tables`; `plans` first.
/// Ties break alphabetically so the order is stable.
fn insert_order(tables: &[String], fk_edges: &[(String, String)]) -> Result<Vec<String>, String> {
    let set: BTreeSet<&str> = tables.iter().map(String::as_str).collect();
    let mut parents: BTreeMap<&str, BTreeSet<&str>> = set.iter().map(|t| (*t, BTreeSet::new())).collect();
    for (child, parent) in fk_edges {
        if child != parent && set.contains(child.as_str()) && set.contains(parent.as_str()) {
            parents.get_mut(child.as_str()).unwrap().insert(parent.as_str());
        }
    }
    let mut out: Vec<String> = Vec::new();
    let mut done: HashSet<&str> = HashSet::new();
    if set.contains(PLANS) && parents[PLANS].is_empty() {
        out.push(PLANS.to_string());
        done.insert(PLANS);
    }
    while out.len() < set.len() {
        let next = set
            .iter()
            .find(|t| !done.contains(**t) && parents[**t].iter().all(|p| done.contains(p)));
        match next {
            Some(t) => {
                out.push(t.to_string());
                done.insert(t);
            }
            None => {
                let stuck: Vec<&str> = set.iter().filter(|t| !done.contains(**t)).copied().collect();
                return Err(format!(
                    "copy-plan: foreign-key cycle among tables {} — cannot order the inserts",
                    stuck.join(", ")
                ));
            }
        }
    }
    Ok(out)
}

fn skip_reason(table: &str) -> Option<&'static str> {
    SKIPPED_TABLES.iter().find(|(t, _)| *t == table).map(|(_, r)| *r)
}

fn generator_for(table: &str) -> Option<fn() -> String> {
    TEXT_PK_GENERATORS.iter().find(|(t, _)| *t == table).map(|(_, g)| *g)
}

/// Mint one fresh id per old id with `gen`, never reusing an old id or a
/// previously minted one.
fn fresh_map(old: &[String], generator: fn() -> String) -> Vec<(String, String)> {
    let mut used: HashSet<String> = old.iter().cloned().collect();
    old.iter()
        .map(|o| {
            let mut id = generator();
            while used.contains(&id) {
                id = generator();
            }
            used.insert(id.clone());
            (o.clone(), id)
        })
        .collect()
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Group {
    Plan,
    Booking,
    ActivityKeyed,
}

/// Everything needed to copy one table, settled before any write.
struct TablePlan {
    table: String,
    group: Group,
    columns: Vec<ColumnInfo>,
    rows: i64,
    refs: i64,
    omit: Option<String>,
    text_pk: Option<String>,
    fresh_pk: Option<(String, Vec<(String, String)>)>,
}

pub async fn run(args: &[String]) -> Result<(), String> {
    let a = parse_args(args)?;
    validate_plan_id(&a.dst)?;
    if a.src == a.dst {
        return Err("copy-plan: source and destination plan ids are the same".to_string());
    }

    let conn = if a.dry_run {
        crate::db::connect_read().await?
    } else {
        crate::db::connect_write()
            .await
            .map_err(|e| format!("failed to connect to Turso (write tier): {e}"))?
    };

    // ── 1. source / destination plan rows ─────────────────────────────
    let Some((src_version, src_deleted)) = pc::plan_version(&conn, &a.src).await? else {
        return Err(format!(
            "copy-plan: source plan '{}' not found in plans (run `travel plans` to list plans)",
            a.src
        ));
    };
    if src_deleted {
        return Err(format!(
            "copy-plan: source plan '{}' is soft-deleted; refusing to copy a deleted plan",
            a.src
        ));
    }
    if pc::plan_version(&conn, &a.dst).await?.is_some() {
        return Err(format!("copy-plan: destination plan '{}' already exists in plans", a.dst));
    }
    // The booking ledger keys a plan by trip id ('-' -> '_'), so two plan ids that
    // map to the same trip id would share (and resync over) one ledger — even
    // while that ledger is still empty.
    let trip_owners = pc::plans_with_trip_id(&conn, &trip_id_of(&a.dst)).await?;
    if !trip_owners.is_empty() {
        return Err(format!(
            "copy-plan: destination '{}' maps to booking trip id '{}', which plan(s) {} already use; pick another id",
            a.dst,
            trip_id_of(&a.dst),
            trip_owners.join(", ")
        ));
    }

    // ── 2. live schema ────────────────────────────────────────────────
    let scoped = plan_schema::plan_scoped_tables(&conn).await?;
    let columns = plan_schema::all_table_columns(&conn).await?;
    let fk_edges = plan_schema::foreign_key_edges(&conn).await?;
    let cols_of = |t: &str| -> Result<&Vec<ColumnInfo>, String> {
        columns
            .get(t)
            .ok_or_else(|| format!("copy-plan: no column info for table {t}"))
    };
    let has_col = |t: &str, c: &str| columns.get(t).is_some_and(|cs| cs.iter().any(|x| x.name == c));
    let scoped_set: HashSet<&str> = scoped.iter().map(String::as_str).collect();
    let booking_tables: Vec<String> = columns
        .keys()
        .filter(|t| !scoped_set.contains(t.as_str()) && has_col(t, BOOKING_KEY))
        .cloned()
        .collect();
    let activity_tables: Vec<String> = columns
        .keys()
        .filter(|t| {
            !scoped_set.contains(t.as_str()) && !booking_tables.contains(t) && has_col(t, ACTIVITY_ID)
        })
        .cloned()
        .collect();

    let src_trip = trip_id_of(&a.src);
    let dst_trip = trip_id_of(&a.dst);
    let src_prefix = format!("{src_trip}:");
    let dst_prefix = format!("{dst_trip}:");

    // ── 3. destination must be empty everywhere ───────────────────────
    let mut dst_items: Vec<CountItem> = Vec::new();
    for t in &scoped {
        dst_items.push(CountItem {
            label: t,
            table: t,
            columns: cols_of(t)?,
            selection: Selection::Equals { column: PLAN_ID, value: &a.dst },
            exclude: &[],
        });
    }
    for t in &booking_tables {
        dst_items.push(CountItem {
            label: t,
            table: t,
            columns: cols_of(t)?,
            selection: Selection::Prefix { column: BOOKING_KEY, prefix: &dst_prefix },
            exclude: &[],
        });
        if has_col(t, TRIP_ID) {
            dst_items.push(CountItem {
                label: t,
                table: t,
                columns: cols_of(t)?,
                selection: Selection::Equals { column: TRIP_ID, value: &dst_trip },
                exclude: &[],
            });
        }
    }
    let occupied: Vec<String> = pc::count(&conn, &dst_items, &[])
        .await?
        .into_iter()
        .filter(|(_, n, _)| *n > 0)
        .map(|(t, n, _)| format!("{t}={n}"))
        .collect();
    if !occupied.is_empty() {
        return Err(format!(
            "copy-plan: destination '{}' (trip id {dst_trip}) already has rows: {}. Refusing to merge into existing data.",
            a.dst,
            occupied.join(" ")
        ));
    }

    // ── 4. booking ledger consistency for the source trip ─────────────
    for t in &booking_tables {
        if has_col(t, TRIP_ID) {
            let bad = pc::trip_key_mismatches(&conn, t, BOOKING_KEY, TRIP_ID, &src_trip, &src_prefix).await?;
            if bad > 0 {
                return Err(format!(
                    "copy-plan: {t} has {bad} row(s) where trip_id '{src_trip}' and the booking_key prefix '{src_prefix}' disagree; fix the ledger before copying"
                ));
            }
        }
    }

    // ── 5. activity id map (the one map every group shares) ───────────
    let activity_map: Vec<(String, String)> = if scoped_set.contains(ACTIVITIES) {
        match pc::classify_pk(cols_of(ACTIVITIES)?, PLAN_ID) {
            PkKind::SingleText(pk) => {
                let old = pc::plan_column_values(&conn, ACTIVITIES, &pk, &a.src).await?;
                let generator = generator_for(ACTIVITIES)
                    .ok_or("copy-plan: no id generator registered for activities")?;
                fresh_map(&old, generator)
            }
            other => {
                return Err(format!(
                    "copy-plan: activities primary key changed shape ({other:?}); the activity-id remap needs a single TEXT id"
                ));
            }
        }
    } else {
        Vec::new()
    };
    let act_lookup: HashMap<&str, &str> = activity_map
        .iter()
        .map(|(o, n)| (o.as_str(), n.as_str()))
        .collect();

    // ── 6. per-table plans (PK shape) + one combined source count ─────
    let mut plans: Vec<TablePlan> = Vec::new();
    let mut skipped: Vec<(String, &'static str)> = Vec::new();
    for t in &scoped {
        if let Some(reason) = skip_reason(t) {
            skipped.push((t.clone(), reason));
            continue;
        }
        plans.push(new_table_plan(t, Group::Plan, cols_of(t)?.clone(), PLAN_ID));
    }
    for t in &booking_tables {
        plans.push(new_table_plan(t, Group::Booking, cols_of(t)?.clone(), BOOKING_KEY));
    }
    for t in &activity_tables {
        plans.push(new_table_plan(t, Group::ActivityKeyed, cols_of(t)?.clone(), ACTIVITY_ID));
    }

    // Columns NOT counted as activity-id references: exactly the ones the copy
    // statement rewrites some other way (key, constant, omitted or fresh PK).
    let excludes: Vec<Vec<&str>> = plans
        .iter()
        .map(|p| {
            let mut ex: Vec<&str> = match p.group {
                Group::Plan => vec![PLAN_ID],
                Group::Booking => vec![BOOKING_KEY, TRIP_ID],
                Group::ActivityKeyed => vec![ACTIVITY_ID],
            };
            ex.extend(p.omit.as_deref());
            ex.extend(p.text_pk.as_deref());
            ex
        })
        .collect();
    let mut src_items: Vec<CountItem> = Vec::new();
    for (p, ex) in plans.iter().zip(&excludes) {
        let selection = match p.group {
            Group::Plan => Selection::Equals { column: PLAN_ID, value: &a.src },
            Group::Booking => Selection::Prefix { column: BOOKING_KEY, prefix: &src_prefix },
            Group::ActivityKeyed => Selection::InActMap { column: ACTIVITY_ID },
        };
        src_items.push(CountItem {
            label: &p.table,
            table: &p.table,
            columns: &p.columns,
            selection,
            exclude: ex,
        });
    }
    for (t, _) in &skipped {
        src_items.push(CountItem {
            label: t,
            table: t,
            columns: cols_of(t)?,
            selection: Selection::Equals { column: PLAN_ID, value: &a.src },
            exclude: &[],
        });
    }
    let counts = pc::count(&conn, &src_items, &activity_map).await?;
    let count_of: HashMap<String, (i64, i64)> =
        counts.into_iter().map(|(t, n, r)| (t, (n, r))).collect();
    for p in plans.iter_mut() {
        let (n, r) = count_of.get(&p.table).copied().unwrap_or((0, 0));
        p.rows = n;
        p.refs = r;
    }
    let skipped_rows: Vec<(String, &'static str, i64)> = skipped
        .iter()
        .map(|(t, r)| (t.clone(), *r, count_of.get(t).map(|c| c.0).unwrap_or(0)))
        .collect();

    // ── 7. settle the PK of every table that has rows ─────────────────
    for p in plans.iter_mut().filter(|p| p.rows > 0) {
        let key = match p.group {
            Group::Plan => PLAN_ID,
            Group::Booking => BOOKING_KEY,
            Group::ActivityKeyed => ACTIVITY_ID,
        };
        match pc::classify_pk(&p.columns, key) {
            PkKind::IncludesKey | PkKind::NoPk => {}
            PkKind::SingleInteger(c) => p.omit = Some(c),
            PkKind::SingleText(c) if p.group == Group::Plan => {
                if p.table == ACTIVITIES {
                    p.fresh_pk = Some((c, activity_map.clone()));
                } else {
                    let generator = generator_for(&p.table).ok_or_else(|| {
                        format!(
                            "copy-plan: {} has a single TEXT primary key ({c}) and {} row(s), but no id generator is registered for it in TEXT_PK_GENERATORS; refusing to invent an id format",
                            p.table, p.rows
                        )
                    })?;
                    let old = pc::plan_column_values(&conn, &p.table, &c, &a.src).await?;
                    p.fresh_pk = Some((c, fresh_map(&old, generator)));
                }
            }
            other => {
                return Err(format!(
                    "copy-plan: {} ({} row(s)) has a primary key copy-plan cannot copy safely: {other:?}",
                    p.table, p.rows
                ));
            }
        }
    }

    // ── 8. booking key map ────────────────────────────────────────────
    let old_keys = pc::prefixed_values(&conn, &booking_tables, BOOKING_KEY, &src_prefix).await?;
    let mut key_map: Vec<(String, String)> = Vec::new();
    let mut keys_with_activity = 0usize;
    for k in &old_keys {
        let new = rewrite_booking_key(k, &src_prefix, &dst_prefix, &act_lookup)
            .ok_or_else(|| format!("copy-plan: booking key '{k}' lost its '{src_prefix}' prefix"))?;
        let plain = format!("{dst_prefix}{}", &k[src_prefix.len()..]);
        if new != plain {
            keys_with_activity += 1;
        }
        key_map.push((k.clone(), new));
    }

    // ── 9. insert order: parents before children ──────────────────────
    let names: Vec<String> = plans.iter().filter(|p| p.rows > 0).map(|p| p.table.clone()).collect();
    let order = insert_order(&names, &fk_edges)?;

    let report = Report {
        a: &a,
        src_version,
        plans: &plans,
        order: &order,
        skipped: &skipped_rows,
        activity_ids: activity_map.len(),
        booking_keys: key_map.len(),
        keys_with_activity,
        src_prefix: &src_prefix,
        dst_prefix: &dst_prefix,
    };

    // Read before BEGIN: once COMMIT succeeds, nothing may turn the run into a
    // reported failure (a retry would then hit "destination already exists").
    let upcoming = crate::mark_plan_deleted::upcoming_anchor_end(&conn, &a.src).await?;
    if a.dry_run {
        report.print(None, upcoming.as_deref());
        return Ok(());
    }

    // ── 10. write: one transaction ────────────────────────────────────
    let fault = std::env::var(FAULT_ENV).ok().filter(|v| !v.is_empty());
    conn.execute("BEGIN", libsql::params![])
        .await
        .map_err(|e| format!("copy-plan BEGIN failed: {e}"))?;
    let outcome = write_all(&conn, &a, src_version, &plans, &order, &key_map, &activity_map, &dst_trip, fault.as_deref()).await;
    let run_id = match outcome {
        Ok(run_id) => {
            if let Err(e) = conn.execute("COMMIT", libsql::params![]).await {
                let _ = conn.execute("ROLLBACK", libsql::params![]).await;
                return Err(format!(
                    "copy-plan COMMIT failed: {e}\n(the transaction was not confirmed; check whether '{}' exists with `travel plans` before retrying — a retry fails loud if it does)",
                    a.dst
                ));
            }
            run_id
        }
        Err(e) => {
            let rb = conn.execute("ROLLBACK", libsql::params![]).await;
            let rb_note = match rb {
                Ok(_) => "rolled back — nothing was written".to_string(),
                Err(re) => format!("ROLLBACK reported: {re}; the open transaction is discarded by the server, nothing was committed"),
            };
            return Err(format!("copy-plan failed: {e}\n({rb_note})"));
        }
    };

    report.print(Some(&run_id), upcoming.as_deref());
    Ok(())
}

fn new_table_plan(table: &str, group: Group, columns: Vec<ColumnInfo>, key: &str) -> TablePlan {
    // PK shape is settled in step 7 (only tables with rows need it); the omit /
    // text-PK columns are noted here so the count query leaves them out of the
    // activity-id reference count.
    let (omit, text_pk) = match pc::classify_pk(&columns, key) {
        PkKind::SingleInteger(c) => (Some(c), None),
        PkKind::SingleText(c) => (None, Some(c)),
        _ => (None, None),
    };
    TablePlan {
        table: table.to_string(),
        group,
        columns,
        rows: 0,
        refs: 0,
        omit,
        text_pk,
        fresh_pk: None,
    }
}

#[allow(clippy::too_many_arguments)]
async fn write_all(
    conn: &libsql::Connection,
    a: &Args,
    src_version: i64,
    plans: &[TablePlan],
    order: &[String],
    key_map: &IdMap,
    activity_map: &IdMap,
    dst_trip: &str,
    fault: Option<&str>,
) -> Result<String, String> {
    let by_name: HashMap<&str, &TablePlan> = plans.iter().map(|p| (p.table.as_str(), p)).collect();
    for t in order {
        if fault == Some(t.as_str()) {
            return Err(format!("{FAULT_ENV}={t}: injected failure before copying {t}"));
        }
        let p = by_name[t.as_str()];
        let trip_const = [(TRIP_ID, dst_trip)];
        let source = match p.group {
            Group::Plan => Source::Plan { src: &a.src, dst: &a.dst },
            Group::Booking => Source::KeyMap { column: BOOKING_KEY, map: key_map },
            Group::ActivityKeyed => Source::KeyMap { column: ACTIVITY_ID, map: activity_map },
        };
        let constants: &[(&str, &str)] = if p.group == Group::Booking && p.columns.iter().any(|c| c.name == TRIP_ID) {
            &trip_const
        } else {
            &[]
        };
        let q = pc::build_copy(&CopyStatement {
            table: &p.table,
            columns: &p.columns,
            source,
            constants,
            omit: p.omit.as_deref(),
            fresh_pk: p.fresh_pk.as_ref().map(|(c, m)| (c.as_str(), m.as_slice())),
            actmap: activity_map,
        });
        let n = pc::execute(conn, &q)
            .await
            .map_err(|e| format!("copying {t} failed: {e}"))?;
        if n as i64 != p.rows {
            return Err(format!(
                "copying {t}: inserted {n} row(s) but planned {} — the source changed during the copy",
                p.rows
            ));
        }
    }
    let now_db = now_db_datetime();
    let run_id = record_operation(
        conn,
        &a.dst,
        "copy-plan",
        &format!("copied from {}", a.src),
        src_version,
        src_version + 1,
        &now_db,
    )
    .await
    .map_err(|e| format!("audit row failed: {e}"))?;
    if fault == Some("commit") {
        return Err(format!("{FAULT_ENV}=commit: injected failure before COMMIT"));
    }
    Ok(run_id)
}

struct Report<'a> {
    a: &'a Args,
    src_version: i64,
    plans: &'a [TablePlan],
    order: &'a [String],
    skipped: &'a [(String, &'static str, i64)],
    activity_ids: usize,
    booking_keys: usize,
    keys_with_activity: usize,
    src_prefix: &'a str,
    dst_prefix: &'a str,
}

impl Report<'_> {
    fn print(&self, run_id: Option<&str>, upcoming_end: Option<&str>) {
        let dry = run_id.is_none();
        let verb = if dry { "would copy" } else { "copied" };
        let a = self.a;
        println!(
            "copy-plan {} -> {}{}",
            a.src,
            a.dst,
            if dry { "  [DRY RUN: nothing written]" } else { "" }
        );
        let width = self
            .plans
            .iter()
            .map(|p| p.table.len())
            .chain(self.skipped.iter().map(|s| s.0.len()))
            .max()
            .unwrap_or(10);
        let by_name: HashMap<&str, &TablePlan> = self.plans.iter().map(|p| (p.table.as_str(), p)).collect();
        let line = |p: &TablePlan| {
            let mut notes = Vec::new();
            if let Some((c, m)) = &p.fresh_pk {
                notes.push(format!("{} fresh {c}(s)", m.len()));
            }
            if p.omit.is_some() {
                notes.push("new rowid".to_string());
            }
            if p.refs > 0 {
                notes.push(format!("{} activity-id ref(s) remapped", p.refs));
            }
            let notes = if notes.is_empty() { String::new() } else { format!("  ({})", notes.join("; ")) };
            println!("  {:<width$} {:>6}{notes}", p.table, p.rows);
        };
        for (group, title) in [
            (Group::Plan, "plan tables (plan_id rewritten):".to_string()),
            (
                Group::Booking,
                format!("booking ledger (key prefix {} -> {}, trip_id rewritten):", self.src_prefix, self.dst_prefix),
            ),
            (Group::ActivityKeyed, "activity-keyed tables (activity_id remapped):".to_string()),
        ] {
            println!("{title}");
            let rows: Vec<&&TablePlan> = self
                .order
                .iter()
                .filter_map(|t| by_name.get(t.as_str()))
                .filter(|p| p.group == group)
                .collect();
            if rows.is_empty() {
                println!("  (no source rows)");
            }
            for p in rows {
                line(p);
            }
        }
        println!("skipped (not copied):");
        for (t, reason, n) in self.skipped {
            println!("  {:<width$} {:>6}  {reason}", t, n);
        }
        let copied_rows: i64 = self.plans.iter().map(|p| p.rows).sum();
        let copied_tables = self.plans.iter().filter(|p| p.rows > 0).count();
        let skipped_rows: i64 = self.skipped.iter().map(|s| s.2).sum();
        println!("summary:");
        println!("  activity ids remapped: {}", self.activity_ids);
        println!(
            "  booking keys rewritten: {} ({} with an embedded activity id remapped)",
            self.booking_keys, self.keys_with_activity
        );
        println!("  total: {verb} {copied_rows} row(s) across {copied_tables} table(s); skipped {skipped_rows} row(s) in {} table(s)", self.skipped.len());
        match run_id {
            Some(id) => println!(
                "  audit: {} version {} (source {} + 1), operation_runs copy-plan run_id {id}",
                a.dst,
                self.src_version + 1,
                self.src_version
            ),
            None => println!(
                "  audit: {} would get version {} (source {} + 1) and one copy-plan operation_runs row",
                a.dst,
                self.src_version + 1,
                self.src_version
            ),
        }
        println!("next steps:");
        if dry {
            println!("  travel copy-plan {} {}", a.src, a.dst);
        }
        println!("  travel snapshot-maps --plan-id {}", a.dst);
        println!("  travel share-token --plan-id {}", a.dst);
        match upcoming_end {
            Some(end) => println!(
                "  travel mark-plan-deleted {} --force    (--force is required: {} has a date anchor ending {end})",
                a.src, a.src
            ),
            None => println!("  travel mark-plan-deleted {}", a.src),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn s(xs: &[&str]) -> Vec<String> {
        xs.iter().map(|x| x.to_string()).collect()
    }

    #[test]
    fn parse_args_positionals_and_dry_run() {
        assert_eq!(
            parse_args(&s(&["a-b", "c-d", "--dry-run"])).unwrap(),
            Args { src: "a-b".into(), dst: "c-d".into(), dry_run: true }
        );
        assert!(parse_args(&s(&["a-b"])).is_err());
        assert!(parse_args(&s(&["a-b", "c-d", "e"])).is_err());
        assert!(parse_args(&s(&["a-b", "c-d", "--force"])).unwrap_err().contains("unknown argument: --force"));
    }

    #[test]
    fn plan_id_validation() {
        for ok in ["kyoto-nov-2026", "a", "a1-b2", "2026"] {
            assert!(validate_plan_id(ok).is_ok(), "{ok}");
        }
        for bad in ["", "Kyoto-nov", "kyoto_nov", "-a", "a-", "a--b", "a b", "kyōto"] {
            assert!(validate_plan_id(bad).is_err(), "{bad:?}");
        }
    }

    #[test]
    fn trip_id_swaps_hyphens() {
        assert_eq!(trip_id_of("osaka-nov-2026"), "osaka_nov_2026");
    }

    #[test]
    fn booking_key_rewrite_prefix_and_activity_segment() {
        let mut m = HashMap::new();
        m.insert("a181373a-9e98", "new-act");
        assert_eq!(
            rewrite_booking_key("osaka_nov_2026:osaka_kyoto_2026:transfer:arrival", "osaka_nov_2026:", "kyoto_nov_2026:", &m)
                .as_deref(),
            Some("kyoto_nov_2026:osaka_kyoto_2026:transfer:arrival")
        );
        assert_eq!(
            rewrite_booking_key(
                "osaka_nov_2026:osaka_kyoto_2026:activity:4:noon:a181373a-9e98",
                "osaka_nov_2026:",
                "kyoto_nov_2026:",
                &m
            )
            .as_deref(),
            Some("kyoto_nov_2026:osaka_kyoto_2026:activity:4:noon:new-act")
        );
        // Only whole segments are remapped; a substring match is left alone.
        assert_eq!(
            rewrite_booking_key("osaka_nov_2026:x:a181373a-9e98z", "osaka_nov_2026:", "k:", &m).as_deref(),
            Some("k:x:a181373a-9e98z")
        );
        // A key from another trip (even one sharing a name prefix) is not rewritten.
        assert_eq!(rewrite_booking_key("osaka_nov_2026b:x", "osaka_nov_2026:", "k:", &m), None);
    }

    #[test]
    fn insert_order_puts_plans_and_parents_first() {
        let tables = s(&["plan_offer_group_meta", "plan_offers", "plans", "activities"]);
        let edges = vec![("plan_offer_group_meta".to_string(), "plan_offers".to_string())];
        let order = insert_order(&tables, &edges).unwrap();
        assert_eq!(order[0], "plans");
        let pos = |t: &str| order.iter().position(|x| x == t).unwrap();
        assert!(pos("plan_offers") < pos("plan_offer_group_meta"));
        assert_eq!(order.len(), 4);
    }

    #[test]
    fn insert_order_rejects_cycles() {
        let tables = s(&["a", "b"]);
        let edges = vec![("a".to_string(), "b".to_string()), ("b".to_string(), "a".to_string())];
        assert!(insert_order(&tables, &edges).unwrap_err().contains("cycle"));
    }

    #[test]
    fn fresh_map_never_reuses_ids() {
        let old = s(&["x", "y", "z"]);
        let m = fresh_map(&old, new_run_id);
        let news: HashSet<&String> = m.iter().map(|(_, n)| n).collect();
        assert_eq!(news.len(), 3);
        assert!(m.iter().all(|(o, n)| o != n));
    }

    #[test]
    fn skip_list_is_documented_and_known() {
        for t in ["map_artifacts", "map_legend_stops", "plan_map_snapshots", "plan_share_tokens"] {
            assert!(skip_reason(t).is_some_and(|r| !r.is_empty()), "{t}");
        }
        assert!(skip_reason("activities").is_none());
    }
}
